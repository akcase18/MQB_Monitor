"""PlatformIO pre-build script for env:esp32c3 and env:dash_s3 (whose
in-process relay serves the same page): gzips the phone
configurator page (platform/esp32/web/index.html) into a C header the
firmware serves as-is (see platform/esp32/src/config_web.cpp).

Runs on every build, so editing the page needs nothing more than a
rebuild. The header goes in the build directory, not the source tree --
it's an output, and keeping it out of git means it can't go stale.
"""

import gzip
import os

Import("env")  # noqa: F821 -- injected by PlatformIO/SCons

SOURCE = os.path.join(env.subst("$PROJECT_DIR"), "platform", "esp32", "web", "index.html")  # noqa: F821
OUT_DIR = os.path.join(env.subst("$BUILD_DIR"), "web_gen")  # noqa: F821
OUT = os.path.join(OUT_DIR, "web_index_gz.h")


def render_header(data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i : i + 16]) + ",")
    return (
        "/* Generated by tools/web/embed_web.py from platform/esp32/web/index.html"
        " -- do not edit. */\n"
        "#pragma once\n\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n\n"
        "static const uint8_t WEB_INDEX_GZ[] = {\n" + "\n".join(lines) + "\n};\n"
        "static const size_t WEB_INDEX_GZ_LEN = sizeof(WEB_INDEX_GZ);\n"
    )


with open(SOURCE, "rb") as f:
    page = f.read()

# mtime=0 so an unchanged page produces a byte-identical header and
# doesn't force a recompile.
header = render_header(gzip.compress(page, compresslevel=9, mtime=0))

os.makedirs(OUT_DIR, exist_ok=True)
existing = None
if os.path.exists(OUT):
    with open(OUT) as f:
        existing = f.read()
if existing != header:
    with open(OUT, "w") as f:
        f.write(header)

env.Append(CPPPATH=[OUT_DIR])  # noqa: F821
