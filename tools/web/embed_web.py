"""PlatformIO pre-build script for env:esp32c3 and env:dash_s3 (whose
in-process relay serves the same page): gzips each web page below into a
C header the firmware serves as-is (see platform/esp32/src/config_web.cpp).

  platform/esp32/web/index.html   -> web_index_gz.h   (phone configurator)
  platform/dash_s3/web/update.html -> web_update_gz.h (firmware update)

Both headers are generated for every env that runs this; only the dash
includes the update page's (platform/dash_s3/src/dash_s3_ota.cpp).

Runs on every build, so editing a page needs nothing more than a rebuild.
The headers go in the build directory, not the source tree -- they're
outputs, and keeping them out of git means they can't go stale.
"""

import gzip
import os

Import("env")  # noqa: F821 -- injected by PlatformIO/SCons

PROJECT_DIR = env.subst("$PROJECT_DIR")  # noqa: F821
OUT_DIR = os.path.join(env.subst("$BUILD_DIR"), "web_gen")  # noqa: F821

# (source, header, C symbol prefix)
PAGES = [
    (os.path.join("platform", "esp32", "web", "index.html"), "web_index_gz.h", "WEB_INDEX_GZ"),
    (os.path.join("platform", "dash_s3", "web", "update.html"), "web_update_gz.h", "WEB_UPDATE_GZ"),
]


def render_header(source, symbol, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i : i + 16]) + ",")
    return (
        "/* Generated by tools/web/embed_web.py from %s"
        " -- do not edit. */\n"
        "#pragma once\n\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n\n"
        "static const uint8_t %s[] = {\n" % (source.replace(os.sep, "/"), symbol)
        + "\n".join(lines)
        + "\n};\n"
        "static const size_t %s_LEN = sizeof(%s);\n" % (symbol, symbol)
    )


os.makedirs(OUT_DIR, exist_ok=True)

for source, header_name, symbol in PAGES:
    with open(os.path.join(PROJECT_DIR, source), "rb") as f:
        page = f.read()

    # mtime=0 so an unchanged page produces a byte-identical header and
    # doesn't force a recompile.
    header = render_header(source, symbol, gzip.compress(page, compresslevel=9, mtime=0))

    out = os.path.join(OUT_DIR, header_name)
    existing = None
    if os.path.exists(out):
        with open(out) as f:
            existing = f.read()
    if existing != header:
        with open(out, "w") as f:
            f.write(header)

env.Append(CPPPATH=[OUT_DIR])  # noqa: F821
