"""PlatformIO pre-build script for the env:dash_s3 family: stamps what an
OTA update is checked against into a generated header, fw_version.h.
platform/dash_s3/src/dash_s3_firmware.cpp is its only includer; it puts
these in the update descriptor every image carries.

FW_VERSION is `git describe --tags --always --dirty`: a tag when there is
one (tag releases to get readable versions), otherwise the short commit
hash, with "-dirty" for a build from uncommitted changes. Truncated to 31
characters to fit the descriptor's field. The dash shows it on its
"Install?" popup.

FW_PARTITION_LAYOUT is a CRC-32 of the partition table
(board_build.partitions) -- its rows, not its comments or spacing. OTA
only ever writes an app slot, so an image built for a different table has
to go over USB; the dash refuses it by this number. tools/release.py
compares it between releases for the same reason.

FW_FS_PARTITION_BYTES is the LittleFS partition's size, which
dash_s3_firmware.cpp checks the log ring (LOG_CHUNK_COUNT) against at
compile time.

A header rather than -Ds, so a new commit recompiles one file instead of
the whole tree, and it is only rewritten when something actually
changes -- the same trick as tools/web/embed_web.py.
"""

import os
import subprocess
import sys

Import("env")  # noqa: F821 -- injected by PlatformIO/SCons

PROJECT_DIR = env.subst("$PROJECT_DIR")  # noqa: F821
sys.path.insert(0, os.path.join(PROJECT_DIR, "tools"))
from partition_table import fs_bytes, layout_crc, partition_rows  # noqa: E402
OUT_DIR = os.path.join(env.subst("$BUILD_DIR"), "fw_gen")  # noqa: F821
OUT = os.path.join(OUT_DIR, "fw_version.h")

VERSION_MAX = 31  # DashS3FirmwareId::version is char[32]


def describe():
    try:
        out = subprocess.run(
            ["git", "describe", "--tags", "--always", "--dirty"],
            cwd=PROJECT_DIR,
            capture_output=True,
            text=True,
            check=True,
        )
        return out.stdout.strip() or "unknown"
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


version = describe()[:VERSION_MAX]
table = os.path.join(PROJECT_DIR, env.GetProjectOption("board_build.partitions"))  # noqa: F821
rows = partition_rows(table)
header = (
    "/* Generated by tools/fw_version.py -- do not edit. */\n"
    "#pragma once\n\n"
    '#define FW_VERSION "%s"\n' % version
    + "#define FW_PARTITION_LAYOUT 0x%08xu\n" % layout_crc(rows)
    + "#define FW_FS_PARTITION_BYTES 0x%xu\n" % fs_bytes(rows)
)

os.makedirs(OUT_DIR, exist_ok=True)
existing = None
if os.path.exists(OUT):
    with open(OUT) as f:
        existing = f.read()
if existing != header:
    with open(OUT, "w") as f:
        f.write(header)

env.Append(CPPPATH=[OUT_DIR])  # noqa: F821
