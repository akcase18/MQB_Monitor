"""PlatformIO pre-build script for the env:dash_s3 family: stamps the
firmware version into a generated header, fw_version.h, as FW_VERSION.
platform/dash_s3/src/dash_s3_firmware.cpp is its only includer; it puts
the string in the update descriptor that an OTA upload is checked against
and that the dash shows on its "Install?" popup.

The version is `git describe --tags --always --dirty`: a tag when there
is one (tag releases to get readable versions), otherwise the short commit
hash, with "-dirty" for a build from uncommitted changes. Truncated to 31
characters to fit the descriptor's field.

A header rather than a -D, so a new commit recompiles one file instead of
the whole tree, and it is only rewritten when the version actually
changes -- the same trick as tools/web/embed_web.py.
"""

import os
import subprocess

Import("env")  # noqa: F821 -- injected by PlatformIO/SCons

PROJECT_DIR = env.subst("$PROJECT_DIR")  # noqa: F821
OUT_DIR = os.path.join(env.subst("$BUILD_DIR"), "fw_gen")  # noqa: F821
OUT = os.path.join(OUT_DIR, "fw_version.h")

VERSION_MAX = 31  # DashS3FirmwareId::version is char[32]


def describe():
    try:
        out = subprocess.run(
            ["git", "describe", "--tags", "--always", "--dirty"],
            cwd=PROJECT_DIR,
            capture_output=True,
            text=True,
            check=True,
        )
        return out.stdout.strip() or "unknown"
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


version = describe()[:VERSION_MAX]
header = (
    "/* Generated by tools/fw_version.py -- do not edit. */\n"
    "#pragma once\n\n"
    '#define FW_VERSION "%s"\n' % version
)

os.makedirs(OUT_DIR, exist_ok=True)
existing = None
if os.path.exists(OUT):
    with open(OUT) as f:
        existing = f.read()
if existing != header:
    with open(OUT, "w") as f:
        f.write(header)

env.Append(CPPPATH=[OUT_DIR])  # noqa: F821
